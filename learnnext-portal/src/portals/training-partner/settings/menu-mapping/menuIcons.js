/** name → component */
export const MENU_ICONS = Object.fromEntries(LIST.map(([name]) => [name, Lucide[name]]).filter(([, c]) => c));
/** [{ name, Icon, label, words }] in picker order */
export const ICON_OPTIONS = LIST.filter(([name]) => MENU_ICONS[name]).map(([name, words]) => ({ name, Icon: MENU_ICONS[name], label: iconLabel(name), words: `${name} ${words}`.toLowerCase() }));

export const FALLBACK_ICON = Lucide.PanelsTopLeft;
export const menuIcon = (name) => MENU_ICONS[name] ?? FALLBACK_ICON;
/** "MailCheck" → "Mail check" (picker tooltips / labels) */
export function iconLabel(name) {
  return name
    .replace(/([a-z])([A-Z0-9])/g, '$1 $2')
    .replace(/ (\w)/g, (m) => m.toLowerCase())
    .replace(/^./, (c) => c.toUpperCase());
}
